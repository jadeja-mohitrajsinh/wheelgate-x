"""Data models and schemas for WheelGate X according to PRD v2.0 Section 11."""
from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, Mapping

_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
_SHA1_RE = re.compile(r"^[0-9a-f]{40}$")


@dataclass(frozen=True)
class AssessmentRequest:
    """11.1 AssessmentRequest (created server-side from authenticated intake)."""
    assessment_id: str
    github_installation_id: int
    repository_id: int
    pr_number: int
    head_sha: str
    package_name: str
    from_version: str
    to_version: str
    mode: str = "fixture"
    requirements_path: str = "requirements.txt"
    policy_version: str = "startup-v1"
    schema_version: str = "1.0"
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def __post_init__(self):
        if not self.assessment_id:
            raise ValueError("assessment_id cannot be empty")
        if not _SHA1_RE.fullmatch(self.head_sha.lower()):
            raise ValueError(f"Invalid head_sha (must be 40-char lowercase hex): {self.head_sha}")

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class ApprovedBaseline:
    """11.2 ApprovedBaseline (protected configuration loaded independently)."""
    repository_id: int
    package_normalized: str
    baseline_version: str
    wheel_filename: str
    wheel_sha256: str
    approved_by: str
    approved_at: str
    policy_version: str = "startup-v1"
    allowlisted_hooks: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        if not _SHA256_RE.fullmatch(self.wheel_sha256.lower()):
            raise ValueError(f"Invalid wheel_sha256: {self.wheel_sha256}")
        for path, digest in self.allowlisted_hooks.items():
            if not _SHA256_RE.fullmatch(digest.lower()):
                raise ValueError(f"Invalid allowlisted hook digest for {path}: {digest}")

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class HookDiff:
    """11.3 HookDiff (startup hook difference between baseline and candidate)."""
    installed_path: str
    change_type: str  # NEW, MODIFIED, UNCHANGED, REMOVED
    baseline_sha256: str | None
    candidate_sha256: str | None
    executable_import_line_numbers: list[int]
    allowlisted: bool
    reason_code: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class PolicyDecision:
    """11.4 PolicyDecision (authoritative deterministic verdict from validator)."""
    assessment_id: str
    validator_version: str
    policy_version: str
    repository_id: int
    pr_number: int
    head_sha: str
    candidate_filename: str
    candidate_sha256: str
    baseline_sha256: str | None
    verdict: str  # PASS, HOLD, BLOCK
    reason_codes: list[str]
    hook_diffs: list[HookDiff]
    evidence_complete: bool
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def __post_init__(self):
        if self.verdict not in ("PASS", "HOLD", "BLOCK"):
            raise ValueError(f"Unknown verdict: {self.verdict}")

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["hook_diffs"] = [h.to_dict() if isinstance(h, HookDiff) else h for h in self.hook_diffs]
        return d


@dataclass(frozen=True)
class AgentNarrative:
    """11.5 AgentNarrative (non-authoritative narrative generated by agent)."""
    assessment_id: str
    summary: str
    observations: list[str]
    risk_explanation: str
    recommendation: str
    limitations: list[str]
    evidence_refs: list[str]
    model_stated_verdict: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)
